"""Generate the example gallery (docs/docs/examples/gallery.md) and its thumbnails.

The thumbnails are made from the visual test references (tests/visual/reference/<name>.png,
rendered by CI without UI), so they show exactly what each example draws. The page follows
the sections and rows of the Example Index (docs/docs/examples/index.md): every example
there with an image gets a tile that links to its guide page, or to its source on GitHub.

Usage (from the repository root, needs ffmpeg on the PATH):

    python docs/tools/make_gallery.py

Run it again after adding an example (and its reference image) to the index.
"""

import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
INDEX = ROOT / 'docs/docs/examples/index.md'
PAGE = ROOT / 'docs/docs/examples/gallery.md'
THUMBS = ROOT / 'docs/docs/images/gallery'
REFERENCES = ROOT / 'tests/visual/reference'
SOURCE_URL = 'https://github.com/jonaslindemann/ivf2/tree/main/examples/'
THUMB_WIDTH = 480

# Examples without a visual test reference that have a screenshot elsewhere
EXTRA_IMAGES = {'music_scene1': ROOT / 'docs/docs/images/sc_music1.png'}

ROW = re.compile(r'^\|\s*(`[^|]+`)\s*\|\s*([^|]*)\|\s*([^|]*)\|\s*$')
LINK = re.compile(r'\[[^\]]*\]\(([^)]+)\)')


def parse_index():
    """Sections of the index: [(title, [(name, description, link or None), ...]), ...]."""
    sections = []
    for line in INDEX.read_text(encoding='utf-8').splitlines():
        if line.startswith('## '):
            sections.append((line[3:].strip(), []))
            continue
        m = ROW.match(line)
        if not m or not sections:
            continue
        names = re.findall(r'`([^`]+)`', m.group(1))
        description = re.sub(r'`', '', m.group(2)).strip()
        link = LINK.search(m.group(3))
        for name in names:
            sections[-1][1].append((name, description, link.group(1) if link else None))
    return [(title, rows) for title, rows in sections if rows]


def make_thumbnail(name):
    """Thumbnail path relative to the page, or None if the example has no image."""
    source = REFERENCES / f'{name}.png'
    if not source.exists():
        source = EXTRA_IMAGES.get(name)
        if source is None or not source.exists():
            return None
    target = THUMBS / f'{name}.jpg'
    if not target.exists() or target.stat().st_mtime < source.stat().st_mtime:
        THUMBS.mkdir(parents=True, exist_ok=True)
        subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', str(source), '-vf',
                        f'scale={THUMB_WIDTH}:-2', '-q:v', '4', str(target)], check=True)
    return f'../images/gallery/{name}.jpg'


def main():
    lines = [
        '# Example Gallery',
        '',
        '<!-- Generated by docs/tools/make_gallery.py from the Example Index; edit the index, not this page. -->',
        '',
        'Every example with a picture of what it draws, grouped like the [Example Index](index.md). '
        'Click a picture for the guide that explains it (or the source, if there is no guide); '
        'hover for a short description. The pictures are the reference images of the visual tests, '
        'so they show exactly what each program renders.',
        '',
    ]
    missing = []
    for title, rows in parse_index():
        tiles = []
        for name, description, link in rows:
            image = make_thumbnail(name)
            if image is None:
                missing.append(name)
                continue
            target = link or f'{SOURCE_URL}{name}'
            title_text = description.replace('"', "'")
            tiles.append(f'- [![{name}]({image}) {name}]({target} "{title_text}")')
        if not tiles:
            continue
        lines += [f'## {title}', '', '<div class="ivf-gallery ivf-gallery-wide ivf-gallery-sheet" markdown>', '']
        lines += tiles
        lines += ['', '</div>', '']
    PAGE.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'wrote {PAGE.relative_to(ROOT)}')
    if missing:
        print('no image for: ' + ', '.join(missing), file=sys.stderr)


if __name__ == '__main__':
    main()
