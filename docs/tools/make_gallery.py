def web_examples():
    """Examples built for the browser: examples/CMakeLists.txt minus IVF2_WEB_EXCLUDED_EXAMPLES."""
    text = EXAMPLES_CMAKE.read_text(encoding='utf-8')
    excluded = set(re.search(r'set\(IVF2_WEB_EXCLUDED_EXAMPLES([^)]*)\)', text).group(1).split())
    return [name for name in re.findall(r'^\s*ivf2_example_subdirectory\((\w+)\)', text, re.M)
            if name not in excluded]


def update_guides():
    """The "Run in the browser" box of every guide page the index links web examples to."""
    web = set(web_examples())
    pages = {}
    for _, rows in parse_index():
        for name, _, link in rows:
            if not link or link.startswith('http') or name not in web:
                continue
            page = (INDEX.parent / link.partition('#')[0]).resolve()
            pages.setdefault(page, [])
            if name not in pages[page]:
                pages[page].append(name)

    block = re.compile(re.escape(LIVE_BEGIN) + r'.*?' + re.escape(LIVE_END) + r'\n\n?', re.S)
    changed = 0
    for page in sorted(set(pages) | {p.resolve() for p in GUIDES.rglob('*.md') if LIVE_BEGIN in p.read_text(encoding='utf-8')}):
        text = page.read_text(encoding='utf-8')
        new = block.sub('', text)
        names = pages.get(page)
        if names:
            links = ' · '.join(f'[`{name}`]({LIVE_URL}{name}.html)' for name in names)
            box = f'{LIVE_BEGIN}\n!!! example "Run in the browser"\n\n    {links}\n\n{LIVE_END}\n\n'
            # After the page's first paragraph (below the title)
            lines = new.split('\n')
            i = next(k for k, line in enumerate(lines) if line.startswith('# ')) + 1
            while i < len(lines) and not lines[i].strip():
                i += 1
            while i < len(lines) and lines[i].strip():
                i += 1
            new = '\n'.join(lines[:i + 1]) + '\n' + box + '\n'.join(lines[i + 1:])
        if new != text:
            page.write_text(new, encoding='utf-8', newline='\n')
            changed += 1
    print(f'live example links: {sum(len(n) for n in pages.values())} examples on {len(pages)} pages, '
          f'{changed} pages changed')


def main():
    if len(sys.argv) == 3 and sys.argv[1] == '--web':
        make_web_index(pathlib.Path(sys.argv[2]))
        return
    update_guides()
    if len(sys.argv) == 2 and sys.argv[1] == '--guides':
        return
    lines = [
        '# Example Gallery',
        '',
        '<!-- Generated by docs/tools/make_gallery.py from the Example Index; edit the index, not this page. -->',
        '',
        'Every example with a picture of what it draws, grouped like the [Example Index](index.md). '
        'Click a picture for the guide that explains it (or the source, if there is no guide); '
        'hover for a short description. The pictures are the reference images of the visual tests, '
        'so they show exactly what each program renders.',
        '',
        f'**▶ Run** opens the example in your browser (WebGL 2), built from the current sources; '
        f'all of them are on the [start page of the live examples]({LIVE_URL}). '
        'See [Running in the Browser](../getting_started/web.md).',
        '',
    ]
    web = set(web_examples())
    missing = []
    for title, rows in parse_index():
        tiles = []
        for name, description, link in rows:
            image = make_thumbnail(name)
            if image is None:
                missing.append(name)
                continue
            target = link or f'{SOURCE_URL}{name}'
            title_text = description.replace('"', "'")
            tile = f'- [![{name}]({image}) {name}]({target} "{title_text}")'
            if name in web:
                tile += f' [▶ Run]({LIVE_URL}{name}.html){{ .ivf-run title="Run {name} in the browser" }}'
            tiles.append(tile)
        if not tiles:
            continue
        lines += [f'## {title}', '', '<div class="ivf-gallery ivf-gallery-wide ivf-gallery-sheet" markdown>', '']
        lines += tiles
        lines += ['', '</div>', '']
    PAGE.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'wrote {PAGE.relative_to(ROOT)}')
    if missing:
        print('no image for: ' + ', '.join(missing), file=sys.stderr)


if __name__ == '__main__':
    main()
