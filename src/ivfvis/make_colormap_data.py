"""Generates colormap_data.cpp: the built-in colormaps of ivfvis as 256-entry RGB tables.

Run with a Python that has matplotlib (3.5 or later):

    python src/ivfvis/make_colormap_data.py > src/ivfvis/colormap_data.cpp
"""
import matplotlib

MAPS = [
    ("viridis", "viridis", "matplotlib (van der Walt, Smith), CC0"),
    ("magma", "magma", "matplotlib (van der Walt, Smith), CC0"),
    ("inferno", "inferno", "matplotlib (van der Walt, Smith), CC0"),
    ("plasma", "plasma", "matplotlib (van der Walt, Smith), CC0"),
    ("cividis", "cividis", "Nunez, Anderton, Renslow (2018), PLOS ONE 13(7), via matplotlib"),
    ("turbo", "turbo", "Google LLC (Mikhailov 2019), Apache License 2.0, via matplotlib"),
    ("coolwarm", "coolwarm", "Moreland (2009), diverging, via matplotlib"),
]

print("// Generated by make_colormap_data.py from matplotlib %s - do not edit." % matplotlib.__version__)
print("// Sources and licences of the colour data are given per table.")
print()
print("#include \"colormap_data.h\"")
print()
print("namespace ivfvis::detail {")
print()
for name, mpl, source in MAPS:
    cmap = matplotlib.colormaps[mpl]
    print("// %s: %s" % (name, source))
    print("const std::uint8_t %s_data[256][3] = {" % name)
    rows = []
    for i in range(256):
        r, g, b, _ = cmap(i / 255.0)
        rows.append("{%d,%d,%d}" % (round(r * 255), round(g * 255), round(b * 255)))
    for k in range(0, 256, 8):
        print("    " + ", ".join(rows[k:k + 8]) + ",")
    print("};")
    print()
print("} // namespace ivfvis::detail")
